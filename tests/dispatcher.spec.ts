test('commit reads the latest shared storage even without a storage notification', async ({ page }) => {
  const id = await submitPatientBooking(page)
  await approve(page, id)
  await page.goto(`/dispatcher/assignment?booking=${id}`)
  await selectResources(page)
  await page.getByRole('button', { name: 'ตรวจสอบซ้ำและยืนยันการมอบหมาย', exact: true }).click()
  await page.getByRole('button', { name: 'ยืนยันการมอบหมาย', exact: true }).click()
  // A same-document storage write emits no storage event to this document.
  await page.evaluate(() => {
    const state = JSON.parse(localStorage.getItem('ban-klang-transit:demo:v1')!)
    state.vehicles[0].active = false
    localStorage.setItem('ban-klang-transit:demo:v1', JSON.stringify(state))
  })
  await page.getByRole('button', { name: 'ยืนยันการมอบหมาย', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('รถรับส่งไม่พร้อมใช้งาน')
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('ban-klang-transit:demo:v1')!))
  expect(saved.vehicles[0].active).toBe(false)
  expect(saved.bookings[0].schedule).toBeUndefined()
})
