test('inactive and missing resources cannot be assigned and are never silently reactivated', async ({ page }) => {
  const id = await submitPatientBooking(page)
  await approve(page, id)
  await page.evaluate(() => {
    const state = JSON.parse(localStorage.getItem('ban-klang-transit:demo:v1')!)
    state.vehicles.forEach((v: { active: boolean }) => { v.active = false })
    state.drivers.forEach((d: { active: boolean }) => { d.active = false })
    localStorage.setItem('ban-klang-transit:demo:v1', JSON.stringify(state))
  })
  await page.goto(`/dispatcher/assignment?booking=${id}`)
  await page.getByRole('button', { name: /^รถรับส่ง:/ }).click()
  await expect(page.getByRole('option', { name: /รถคันที่ 01/ })).toBeDisabled()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /^คนขับ:/ }).click()
  await expect(page.getByRole('option', { name: /คนขับ A/ })).toBeDisabled()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'ตรวจสอบซ้ำและยืนยันการมอบหมาย', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('กรุณาเลือกรถรับส่งและคนขับก่อนตรวจสอบ')
  await page.evaluate(() => {
    const state = JSON.parse(localStorage.getItem('ban-klang-transit:demo:v1')!)
    state.vehicles = []; state.drivers = []
    localStorage.setItem('ban-klang-transit:demo:v1', JSON.stringify(state))
  })
  await page.reload()
  await page.getByRole('button', { name: /^รถรับส่ง:/ }).click()
  await expect(page.getByRole('listbox')).toHaveText('ไม่มีรถรับส่งในระบบสาธิต')
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('ban-klang-transit:demo:v1')!))
  expect(saved.vehicles).toHaveLength(0)
  expect(saved.bookings[0].status).toBe('approved')
  expect(saved.bookings[0].schedule).toBeUndefined()
})

test('vehicle and driver overlaps include the fixed 20-minute preparation buffer; adjacent windows are allowed', async ({ page }) => {
  const first = await submitPatientBooking(page, '13', '10')
  const second = await submitPatientBooking(page, '14', '20')
  const third = await submitPatientBooking(page, '14', '35')
  for (const id of [first, second, third]) await approve(page, id)
  await assign(page, first)
  await page.goto(`/dispatcher/assignment?booking=${second}`)
  await selectResources(page, '01', 'B')
  await expect(page.locator('.dispatch-availability')).toContainText('Schedule Conflict')
  await page.getByRole('button', { name: 'ตรวจสอบซ้ำและยืนยันการมอบหมาย', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText(`${first} · รถคันที่ 01`)
  await expect(page.getByRole('button', { name: 'ยืนยันการมอบหมาย', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'กลับไปเปลี่ยนรถหรือคนขับ', exact: true }).click()
  await selectResources(page, '02', 'A')
  await page.getByRole('button', { name: 'ตรวจสอบซ้ำและยืนยันการมอบหมาย', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText(`${first} · คนขับ A`)
  await page.screenshot({ path: 'test-results/dispatcher-conflict.png', fullPage: true })
  await page.getByRole('button', { name: 'กลับไปเปลี่ยนรถหรือคนขับ', exact: true }).click()
  await assign(page, second, '02', 'B')
  // First ends 13:10. Third starts 13:10: [start, end) has no overlap.
  await assign(page, third, '01', 'A')
  const bookings = await page.evaluate(() => JSON.parse(localStorage.getItem('ban-klang-transit:demo:v1')!).bookings)
  expect(bookings.every((b: { schedule?: unknown }) => !!b.schedule)).toBe(true)
})

test('the final commit rechecks resources and conflicts after confirmation has opened', async ({ page, context }) => {
  const first = await submitPatientBooking(page)
  const second = await submitPatientBooking(page)
  await approve(page, first)
  await approve(page, second)
  await page.goto(`/dispatcher/assignment?booking=${first}`)
  await selectResources(page)
  await page.getByRole('button', { name: 'ตรวจสอบซ้ำและยืนยันการมอบหมาย', exact: true }).click()
  await page.getByRole('button', { name: 'ยืนยันการมอบหมาย', exact: true }).click()
  const otherDispatcher = await context.newPage()
  await otherDispatcher.clock.setFixedTime(new Date('2026-10-26T03:30:00Z'))
  await assign(otherDispatcher, second)
  await expect(page.locator('.dispatch-availability')).toContainText('Schedule Conflict')
  await page.getByRole('button', { name: 'ยืนยันการมอบหมาย', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Schedule Conflict')
  const bookings = await page.evaluate(() => JSON.parse(localStorage.getItem('ban-klang-transit:demo:v1')!).bookings)
  expect(bookings.find((b: { id: string }) => b.id === first).schedule).toBeUndefined()
  expect(bookings.find((b: { id: string }) => b.id === second).schedule).toBeDefined()
  await page.getByRole('button', { name: 'กลับไปเปลี่ยนรถหรือคนขับ', exact: true }).click()
  await selectResources(page, '02', 'B')
  await page.getByRole('button', { name: 'ตรวจสอบซ้ำและยืนยันการมอบหมาย', exact: true }).click()
  await page.getByRole('button', { name: 'ยืนยันการมอบหมาย', exact: true }).click()
  await otherDispatcher.evaluate(() => {
    const state = JSON.parse(localStorage.getItem('ban-klang-transit:demo:v1')!)
    state.vehicles.find((v: { id: string }) => v.id === 'demo-vehicle-2').active = false
    state.drivers.find((d: { id: string }) => d.id === 'demo-driver-B').active = false
    localStorage.setItem('ban-klang-transit:demo:v1', JSON.stringify(state))
  })
  await expect(page.locator('.dispatch-availability')).toContainText('ไม่พร้อมใช้งาน')
  await page.getByRole('button', { name: 'ยืนยันการมอบหมาย', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('รถรับส่งไม่พร้อมใช้งาน')
  await expect(page.getByRole('dialog')).toContainText('คนขับไม่พร้อมใช้งาน')
})

test('48-hour lead time is measured at submission, and invalid legacy requests cannot be approved', async ({ page }) => {
  const id = await submitPatientBooking(page)
  // Reviewing one day before travel must not invalidate a request submitted four days earlier.
  await page.clock.setFixedTime(new Date('2026-10-29T03:30:00Z'))
  await approve(page, id)
  await expect(page.getByRole('status')).toContainText(`อนุมัติคำขอ ${id}`)
  const bad = await submitPatientBooking(page)
  await page.evaluate(id => {
    const state = JSON.parse(localStorage.getItem('ban-klang-transit:demo:v1')!)
    const booking = state.bookings.find((b: { id: string }) => b.id === id)
    booking.createdAt = new Date(Date.parse(booking.appointmentAt) - 47 * 3600000).toISOString()
    localStorage.setItem('ban-klang-transit:demo:v1', JSON.stringify(state))
  }, bad)
  await page.goto('/dispatcher')
  await page.getByRole('row').filter({ hasText: bad }).getByRole('button', { name: 'ดูรายละเอียด →', exact: true }).click()
  await page.getByRole('button', { name: 'อนุมัติคำขอ', exact: true }).click()
  await expect(page.getByRole('button', { name: 'ยืนยันอนุมัติ', exact: true })).toBeDisabled()
  await expect(page.getByRole('alert')).toContainText('อย่างน้อย 48 ชั่วโมงนับจากเวลาส่งคำขอ')
})

