async function selectPickup(page: Page) {
  await page.getByRole('button', { name: 'เลือกจุดรับบนแผนที่', exact: true }).last().click()
  await expect(page.getByRole('button', { name: 'ยืนยันจุดรับ' })).toBeDisabled()
  await page.getByRole('slider', { name: 'จุดรับบนแผนที่จำลอง' }).focus()
  await page.keyboard.press('ArrowRight')
  await page.getByRole('button', { name: 'ยืนยันจุดรับ' }).click()
}

